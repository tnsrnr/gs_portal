export interface RoadStep {
  id: string;
  label: string;
  title: string;
  text: string;
  bridge: string;
}

export interface Roadmap {
  title: string;
  subtitle: string;
  lead: string;
  steps: RoadStep[];
  next?: { href: string; label: string; text: string };
}

function steps(
  slug: string,
  rows: Array<[label: string, title: string, text: string, bridge: string]>,
): RoadStep[] {
  return rows.map(([label, title, text, bridge], index) => ({
    id: `${slug}-${index + 1}`,
    label,
    title,
    text,
    bridge,
  }));
}

